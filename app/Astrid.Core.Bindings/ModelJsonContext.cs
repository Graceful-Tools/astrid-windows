using System.Text.Json.Serialization;

namespace Astrid.Core.Bindings;

/// <summary>
/// The serialisation metadata for every shape in this assembly, generated at build time rather
/// than discovered at run time (task <c>d24777f5</c>).
/// </summary>
/// <remarks>
/// <para>
/// System.Text.Json's default resolver works a type out by reflecting over it on first use: every
/// property, every attribute, an <c>IL</c> accessor emitted per member. This assembly declares 111
/// records, and the shell touches most of them in the first few seconds — a list of rows, the
/// sidebar, the settings pages behind it — so that discovery happened at startup, on the UI
/// thread, for shapes that were perfectly well known when the app was compiled.
/// </para>
/// <para>
/// The source generator knows them at compile time instead. Both forms of each record are
/// registered, the bare type and <c>List&lt;T&gt;</c>, because the reading side goes through
/// <c>ResponseReader.ReadArray&lt;T&gt;</c> as often as it reads one object, and a
/// <c>List&lt;T&gt;</c> the generator was not told about sends the WHOLE graph under it back to
/// reflection — registering the element type alone would have looked done and changed nothing.
/// </para>
/// <para>
/// This is a list of 222 attributes and it is generated from nothing: a new record needs its two
/// lines here by hand. That is deliberate, and <c>ModelJsonContextTests</c> is what makes it safe
/// — it enumerates the assembly and fails naming anything missing, so forgetting is a red gate
/// rather than a type that quietly costs what it used to.
/// </para>
/// <para>
/// Not the commands. Those records are private to <see cref="Commands"/>, which a context outside
/// it cannot name, and they are small, few, and written once per user gesture rather than once per
/// row. They resolve through the reflection fallback that <see cref="CommandJson.Options"/> keeps
/// behind this — see the chain there, which also catches anything in the shell's own assemblies.
/// </para>
/// <para>
/// The generation options restate <see cref="CommandJson.Options"/> exactly. They have to: when
/// they disagree, the generator's fast path is discarded at run time and the metadata path used
/// instead, which still works and quietly costs more — the failure mode is a silent loss of the
/// thing this file exists for. Every record here also carries an explicit
/// <c>[JsonPropertyName]</c>, so the naming policy decides nothing today; it is stated so that the
/// first record written without one behaves the same as the rest.
/// </para>
/// </remarks>
